export async function fetchTrendingVirals(
  nicheFilter: string = 'Todos',
  customQuery?: string,
  tokenOverride?: string
): Promise<FetchTrendingResult> {
  const settings = getStoredSettings();
  const token = (tokenOverride || settings.apifyToken || '').trim();
  const cleanQuery = (customQuery || '').trim();

  // If Apify token is present, execute real-time Brazilian Apify scraping
  if (token.length > 5) {
    try {
      const apifyResult = await searchTikTokViaApify(token, cleanQuery, nicheFilter);
      if (apifyResult.items && apifyResult.items.length > 0) {
        return {
          items: apifyResult.items,
          source: 'apify',
          message: apifyResult.message || '🇧🇷 Produtos mais vendidos no Brasil e vídeos virais coletados em tempo real via Apify!',
        };
      } else if (apifyResult.message) {
        const baseItems = filterAndSearchLocalItems(nicheFilter, cleanQuery);
        return {
          items: baseItems,
          source: 'calibrated',
          message: apifyResult.message,
        };
      }
    } catch (e: unknown) {
      const errMessage = e instanceof Error ? e.message : String(e);
      console.warn('Erro ao consultar Apify:', errMessage);
      const baseItems = filterAndSearchLocalItems(nicheFilter, cleanQuery);
      return {
        items: baseItems,
        source: 'calibrated',
        message: `Aviso na conexão Apify (${errMessage}). Exibindo Ranking Brasil calibrado dos produtos mais vendidos e seus vídeos virais.`,
      };
    }
  }

  const filtered = filterAndSearchLocalItems(nicheFilter, cleanQuery);

  return {
    items: filtered,
    source: 'calibrated',
    message: '🇧🇷 Ranking Brasil Ativo: Produtos mais vendidos no Brasil + Vídeos Virais bombando (Conecte sua chave Apify para varredura ao vivo).',
  };
}

function filterAndSearchLocalItems(nicheFilter: string, cleanQuery: string): TrendingItem[] {
  let pool =
    nicheFilter === 'Todos'
      ? [...TRENDING_PRODUCTS_MOCK]
      : TRENDING_PRODUCTS_MOCK.filter((item) => item.niche === nicheFilter);

  if (cleanQuery.length > 1) {
    const qLower = cleanQuery.toLowerCase();
    // Ignore generic Brazil tags when filtering local pool so all Brazil top sellers appear
    const isGenericTag =
      qLower.includes('tiktokshopbrasil') ||
      qLower.includes('mais vendidos') ||
      qLower.includes('produtos virais') ||
      qLower.includes('achadinhos shopee');

    if (!isGenericTag) {
      const matched = pool.filter(
        (item) =>
          item.product.toLowerCase().includes(qLower) ||
          item.title.toLowerCase().includes(qLower) ||
          item.niche.toLowerCase().includes(qLower) ||
          item.viralHook.toLowerCase().includes(qLower)
      );

      if (matched.length > 0) {
        pool = matched;
      } else {
        pool = [buildDynamicBrazilSearchItem(cleanQuery, nicheFilter), ...pool.slice(0, 5)];
      }
    }
  }

  return pool.map((item, idx) => ({
    ...item,
    rankPosition: idx + 1,
  }));
}
